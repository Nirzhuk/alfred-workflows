/**
 * Generates src/components/icon/phosphor.ts from the SVG files in
 * src/assets/icons/phosphor/ (Phosphor Icons, regular weight).
 *
 * Usage:
 *   1. Download a new icon into src/assets/icons/phosphor/ (see docs/iconography.md)
 *   2. bun run scripts/generate-phosphor-icons.mjs
 *
 * The generated module maps icon names to their path data so the shared
 * <Icon> component can render them with `currentColor` — no SVG loader
 * plugin and no per-icon React component needed.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const iconsDir = join(root, "src", "assets", "icons", "phosphor");
const outFile = join(root, "src", "components", "icon", "phosphor.ts");

const names = readdirSync(iconsDir)
  .filter((file) => file.endsWith(".svg"))
  .map((file) => file.replace(/\.svg$/, ""))
  .sort();

const entries = names.map((name) => {
  const source = readFileSync(join(iconsDir, `${name}.svg`), "utf8");
  const viewBox = source.match(/viewBox="([^"]+)"/)?.[1] ?? "0 0 256 256";
  const paths = [...source.matchAll(/<path\b([^>]*?)\/>/g)].map((match) => {
    const attrs = match[1];
    const d = attrs.match(/d="([^"]*)"/)?.[1] ?? "";
    const fillRule = attrs.match(/fill-rule="([^"]*)"/)?.[1];
    return fillRule ? { d, fillRule } : { d };
  });
  if (paths.length === 0) {
    throw new Error(`${name}.svg contains no <path> elements`);
  }
  const serialized = paths
    .map(
      (path) =>
        `{ d: ${JSON.stringify(path.d)}${
          path.fillRule ? `, fillRule: ${JSON.stringify(path.fillRule)}` : ""
        } }`,
    )
    .join(", ");
  return `  ${JSON.stringify(name)}: {\n    viewBox: ${JSON.stringify(viewBox)},\n    paths: [${serialized}],\n  },`;
});

const header = `// Generated by scripts/generate-phosphor-icons.mjs — do not edit by hand.
// Source SVGs live in src/assets/icons/phosphor/ (Phosphor Icons, regular
// weight, MIT licensed). See docs/iconography.md for the usage rules.

export type PhosphorIconPath = { d: string; fillRule?: string };

export const PHOSPHOR_ICONS = {
${entries.join("\n")}
} as const;

export type PhosphorIconName = keyof typeof PHOSPHOR_ICONS;
`;

writeFileSync(outFile, header);
console.log(`Wrote ${names.length} icons to ${outFile}`);
